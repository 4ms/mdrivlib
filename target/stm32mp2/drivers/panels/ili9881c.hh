// =============================================================================
//  ER-TFT050-10 (BuyDisplay): 5" IPS, 720(H)x1280(V) portrait, ILI9881C
//  controller, 4-lane MIPI-DSI, RGB888, video mode.
// =============================================================================
// Verified on hardware (stm32mp2-baremetal ltdc-dsi/, 58 fps).
//
// There is no vendor DSI timing table, so the porches below are chosen for
// ~60 Hz. The ILI9881C is tolerant of the exact blanking (HFP was 120; 180-190
// with HBP 20-40 makes it stable).
//
// Clocking chain (HSE = 40 MHz):
//   HSE 40 MHz --/2--> ck_ker_dsiphy 20 MHz --[D-PHY PLL]--> 450 Mbps/lane
//   lane byte clock = 450/8 = 56.25 MHz   (time base for the DSI video regs)
//   DSI pixel throughput = lane_rate*lanes/bpp = 450*4/24 = 75 MHz (max)
//   LTDC pixel clock = ck_ker_ltdc = PLL4/N <= 68 MHz: PLL4 = 1200 MHz -> /18 =
//     66.7 MHz. 66.7 < 75 = the DSI headroom that lets burst mode work.
//     66.7 MHz / (970 * 1316) ~= 52 Hz. (The PoC comments say HTotal 950 /
//     57 Hz; those predate HFP being raised to 190.)
//
// D-PHY PLL: target the 450 Mbps row of ST's PLL regulation table (HAL_DSI_DT_450
// = {hs_freq 0x16, odf /2, vco 0x09, prop 0x0B}; the HAL writes hs_freq/vco/prop
// itself from PhyDataRate). Formula from ST's downstream dw_mipi_dsi-stm.c
// (HWVER_141 = MP25):
//   f_vco     = 20 * 90 / 4       = 450 MHz
//   data_rate = 2*20*90 / (4*2)   = 450 Mbps/lane
//
// PHY timers: hstt_phy_141_table row HSTT(450, clk_lp2hs=65, clk_hs2lp=40,
// data_lp2hs=49, data_hs2lp=23).
//
// The ILI9881C needs LP during vertical blanking as its frame delimiter (holding
// vblank in HS blanks the panel); the driver always enables it.
//
// Init sequence: converted from the vendor's ILI9881C_Initial.h (193 DCS writes).
// 2-byte records are register writes (reg + value); the 4-byte
// {0xFF,0x98,0x81,page} records switch the ILI9881C command page. Ends with TE-on
// (0x35 0x00), sleep-out (0x11) + 120 ms, display-on (0x29).

