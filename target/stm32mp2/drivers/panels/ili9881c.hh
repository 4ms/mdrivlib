{

inline constexpr DsiPanel ER_TFT050_10{
	.name = "ER-TFT050-10 (ILI9881C)",

	.h_active = 720,
	.h_front = 190,
	.h_sync = 20,
	.h_back = 40, // HTotal = 970
	.v_active = 1280,
	.v_front = 20,
	.v_sync = 4,
	.v_back = 12,
	.dsi_vbp_offset = 0,

	.pixel_clk_max_hz = 68'000'000,

	.num_lanes = 4,
	.lane_rate_mbps = 450,
	.pll_ref_khz = 20'000,
	.pll_ndiv = 90,
	.pll_idf = 4,
	.pll_odf = 1, // /2
	.phy_data_rate = HAL_DSI_DT_450,
	.tx_escape_clk_div = 4, // 56.25 / 4 = 14.06 MHz

	.phy_timers =
		{
			.clk_lp2hs = 65,
			.clk_hs2lp = 40,
			.data_lp2hs = 49,
			.data_hs2lp = 23,
			.stop_wait = 10,
		},

	.video_mode = DSI_VID_MODE_BURST,
	.lp_during_active_hblank = true,
	.lp_largest_packet = 4,
	.lp_vact_largest_packet = 0,

	.gated_video_start = false, // verified sequence: video config written into the running host
	.enable_bta = false,

	// RST is active-low: hold asserted 10 ms, release, then let the controller
	// settle (datasheet: >= 10 ms after release; 120 ms used).
	.reset_pre_deassert_us = 0,
	.reset_assert_us = 10'000,
	.reset_settle_us = 120'000,

	.init_seq = ILI9881C::init_seq,
};

static_assert(ER_TFT050_10.is_valid());
static_assert(ER_TFT050_10.num_init_writes() == 193);
static_assert(ER_TFT050_10.h_total() == 970 && ER_TFT050_10.v_total() == 1316);

} // namespace mdrivlib::Panels
